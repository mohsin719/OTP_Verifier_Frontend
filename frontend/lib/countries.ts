export const DEFAULT_COUNTRY = HEROSMS_COUNTRIES[0]; // USA

export function findCountry(idOrNameOrCode?: string | null): CountryItem | undefined {
  if (!idOrNameOrCode) return undefined;
  const q = idOrNameOrCode.toLowerCase().trim();
  return (
    HEROSMS_COUNTRIES.find((c) => c.id === q) ||
    HEROSMS_COUNTRIES.find((c) => c.code.toLowerCase() === q) ||
    HEROSMS_COUNTRIES.find((c) => c.name.toLowerCase().includes(q))
  );
}
